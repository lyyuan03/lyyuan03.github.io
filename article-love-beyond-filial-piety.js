這樣的祭拜不能說沒有意義，但它還沒有真正進入修行。

祭祖若只停留在供品、香火與儀式，就容易讓人以為責任已經完成。可是祖先真正留在後代身上的，不只是一個姓氏，而是許多沒有說完的情緒、沒有處理的創傷，以及一代又一代重複出現的生命模式。

如果你願意在自己這一代停止暴力，學會尊重孩子的選擇，不再用「我是為你好」控制別人的人生；如果你願意重新整理對金錢、婚姻、性別與成功的偏見，那也是祭祖，而且可能是更深的祭祖。

因為你不只記得祖先，你還願意替整個家族承擔一次清醒。

