傳統儒家文化將孝放在人倫秩序的核心。父母生前要奉養，往生後要追思；祖先不只屬於過去，也被安置在家庭的日常生活裡。這套倫理使人記得自己的來處，也維繫了家族的責任感。它有歷史上的意義，不能簡單說成迷信。

