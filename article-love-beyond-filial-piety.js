你是否記得生命不是憑空而來？

你是否看見自己身上有哪些家族留下的資源與傷痕？

你是否願意讓好的部分繼續，讓傷害在自己這一代停止？

當一個人真正進入愛，他不再需要透過祭拜證明自己孝順，也不會因為超越孝順，就輕視祖先與家庭責任。

