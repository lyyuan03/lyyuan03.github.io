有些人一聽見「靈乩」兩個字，腦中立刻浮現的畫面，往往是一個人在香煙瀰漫的神壇前結印、持咒、揮動法器，對著看不見的存在喝令。彷彿聲音愈大、動作愈激烈、儀式愈驚人，就代表他的能力愈高。

