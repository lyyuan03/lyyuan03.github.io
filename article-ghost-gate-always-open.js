每年到了農曆七月,同樣的圖文就會在網路上流傳一輪:鬼門開了,今晚幾點到幾點陰氣最重,哪四個生肖要特別當心,十七件事千萬不能做。多年來我看著這些文章一篇一篇轉發,說真的,我沒有要否定它們。走靈修這條路快三十年,我比誰都清楚,無形的世界確實存在,先民對死亡、對看不見的力量,有一份敬畏,這份敬畏不該被嘲笑。

