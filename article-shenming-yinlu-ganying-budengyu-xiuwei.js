感應可能先發生，修為卻未必已經跟上。

有人感應很強，人格卻不穩；有人沒有明顯的靈動，心性反而十分成熟；也有人早期反應劇烈，經過多年修行之後，才逐漸學會分辨情緒、想像與真正的內在訊息。

