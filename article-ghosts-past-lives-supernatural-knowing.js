我不會把這個「停」理解成退縮，也不會理解成否定靈性經驗。對我來說，它比較像是知道自己的話應該說到哪裡。

我們可以相信，也可以經驗，可以提出自己的理解。只是要知道，哪一段是自己的經驗，哪一段開始進入詮釋，哪一些又只是目前所相信的世界觀。

如果有一天，自己連這幾層都分不清楚，靈修裡最容易出現的混亂就會跟著來。

我現在看一個人的靈修，不太會先看他說自己看過多少、感應多少、知道多少。我會更在意，他能不能處理「我不知道」這四個字。

很多人一進入鬼神、亡靈、前世、天命的世界，就很快把未知變成答案。看到一個影像，就說那是前世；聽到一句話，就說那是神明；身體一動，就說是靈動；人生發生一個巧合，就直接解讀成天意。

有些可能真的如此，有些可能不是。還有一些，也許我們暫時沒有足夠條件判斷。

能把不知道留在那裡，不急著補滿，對我來說也是一種修行。

