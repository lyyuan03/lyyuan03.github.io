你的能力、健康、家人、信任、品格、智慧與願力，不會因為市場一次下跌就全部消失。如果這些仍然存在，那麼真正能夠重新創造財富的根，也仍然存在。

無極瑤池金母在《請問財富》中提醒我們，不要只想占有金錢，而要理解它對生命的重要性。多年後，我愈來愈明白這個教導。

