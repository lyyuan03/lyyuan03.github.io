回想這一個月所有流進來與流出去的錢。有哪些支出，真正改善了你的生活？有哪些消費，只是在安撫焦慮？有哪些收入，來自你真正創造的價值？又有哪些金錢，正在照顧家人、完成理想，或幫助更多的人？

最後，再問自己一個問題：

