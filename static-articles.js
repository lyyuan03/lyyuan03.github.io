有些人會把每一個直覺都說成神諭，把每一次情緒都解釋為神明發怒。當別人不同意時，他便說對方不敬神；當自己的決定出錯時，又說凡人無法理解神意。

這時候，看起來是神明的權威，實際上可能是人的自我躲在神明後面，變得更加巨大。

神格不是一個人自己宣布就能成立的。靈動幾次、做過幾場法事，或被人稱呼為老師，都不能讓一個人從此超越普通人的位置。

真正重要的是：當神明靠近你的生命之後，你有沒有變得更清醒、更穩定，也更知道自己的界線？

