它的意思是：我知道自己目前站在哪裡，也知道什麼樣的風險不應該承擔。

當一個人不知道什麼叫作足夠，再多的錢也只能帶來更大的不安。因為他的注意力永遠放在別人擁有什麼，而不是自己真正需要什麼。

但是，當你知道什麼是足夠，就不必把每一次行情都當成人生最後一次翻身的機會。

你可以錯過一段上漲，也可以保留現金；可以承認看不懂，也可以選擇不參與。

能夠不做，是投資裡最困難的能力之一。

